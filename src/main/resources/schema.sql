-- =====================================================
-- Справочники без внешних ключей — создаём первыми
-- =====================================================

-- Пользователи
CREATE TABLE IF NOT EXISTS USERS
(
    ID       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL    VARCHAR NOT NULL UNIQUE,
    LOGIN    VARCHAR NOT NULL UNIQUE,
    NAME     VARCHAR NOT NULL,
    BIRTHDAY DATE
);

-- Рейтинги MPA
CREATE TABLE IF NOT EXISTS MPA
(
    ID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR NOT NULL
);

-- Жанры
CREATE TABLE IF NOT EXISTS GENRES
(
    ID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR NOT NULL
);

-- =====================================================
-- Фильмы: ссылаются на MPA
-- =====================================================
CREATE TABLE IF NOT EXISTS FILMS
(
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME         VARCHAR NOT NULL,
    DESCRIPTION  VARCHAR,
    RELEASE_DATE DATE,
    DURATION     BIGINT,
    MPA_ID       BIGINT REFERENCES MPA (ID)
);

-- =====================================================
-- Таблицы-связки (многие-ко-многим)
-- =====================================================

-- Жанры фильма
CREATE TABLE IF NOT EXISTS FILMS_GENRES
(
    FILM_ID  BIGINT NOT NULL REFERENCES FILMS (ID) ON DELETE CASCADE,
    GENRE_ID BIGINT NOT NULL REFERENCES GENRES (ID) ON DELETE CASCADE,
    PRIMARY KEY (FILM_ID, GENRE_ID)
);

-- Лайки фильмов
CREATE TABLE IF NOT EXISTS FILMS_LIKES
(
    FILM_ID BIGINT NOT NULL REFERENCES FILMS (ID) ON DELETE CASCADE,
    USER_ID BIGINT NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
    PRIMARY KEY (FILM_ID, USER_ID)
);

-- Дружба между пользователями
CREATE TABLE IF NOT EXISTS USERS_FRIENDS
(
    USER_ID   BIGINT  NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
    FRIEND_ID BIGINT  NOT NULL REFERENCES USERS (ID) ON DELETE CASCADE,
    STATUS    VARCHAR NOT NULL CHECK (STATUS IN ('CONFIRMED', 'UNCONFIRMED')), -- статус дружбы
    PRIMARY KEY (USER_ID, FRIEND_ID)
);